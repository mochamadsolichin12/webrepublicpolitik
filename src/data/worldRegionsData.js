// Helper to obtain complete country data from a GeoJSON feature (or synthesize dynamically)
export const getWorldCountryData = (feature) => {
  if (!feature || !feature.properties) {
    return WORLD_REGIONS[0];
  }
  const p = feature.properties;
  const name = p.name || p.admin || p.sovereignt || 'Kawasan Internasional';
  const iso2 = (p.iso_a2 && p.iso_a2 !== '-99') ? p.iso_a2 : '';
  const iso3 = (p.iso_a3 && p.iso_a3 !== '-99') ? p.iso_a3 : (p.adm0_a3 || '');

  // 1. Check curated list
  const curated = WORLD_REGIONS.find((w) => {
    if (iso2 && w.iso2 && w.iso2.toLowerCase() === iso2.toLowerCase()) return true;
    if (iso3 && w.iso3 && w.iso3.toLowerCase() === iso3.toLowerCase()) return true;
    if (w.name.toLowerCase() === name.toLowerCase()) return true;
    if (w.id.toLowerCase() === name.toLowerCase().replace(/[^a-z0-9]/g, '_')) return true;
    return false;
  });

  if (curated) {
    return curated;
  }

  // 2. Synthesize dynamic country data from GeoJSON properties
  const localizedName = COUNTRY_NAMES_ID[name] || p.formal_en || name;
  const capital = CAPITALS_MAP[name] || 'Pusat Pemerintahan';
  const flag = isoToFlag(iso2);
  const sector = getSectorFromContinent(p.continent, p.subregion);
  const popMillions = p.pop_est && p.pop_est > 0 ? (p.pop_est / 1e6).toFixed(1) : '15.0';
  
  // Calculate simulated military power (60 - 89) based on population & economy
  const gdp = p.gdp_md_est || 50000;
  const baseMil = Math.min(88, Math.max(60, Math.round(55 + Math.log10(Math.max(100, gdp)) * 7)));

  let bloc = 'PBB • Gerakan Non-Blok';
  if (p.continent === 'Europe') bloc = 'Eropa • Mitra Internasional';
  else if (p.continent === 'North America' || p.continent === 'South America') bloc = 'Benua Amerika';
  else if (p.subregion === 'South-Eastern Asia') bloc = 'ASEAN • Asia Pasifik';
  else if (p.continent === 'Africa') bloc = 'Uni Afrika • Non-Blok';

  return {
    id: (iso3 || name).toLowerCase().replace(/[^a-z0-9]/g, '_'),
    iso2,
    iso3,
    name: localizedName,
    capital,
    flag,
    sector,
    lat: 0,
    lng: 0,
    population: Number(popMillions),
    bloc,
    diplomaticStatus: 'Hubungan Diplomatik Resmi RI',
    dominantResource: p.economy ? `${p.economy.replace(/^[0-9]\.\s*/, '')} & Sumber Daya Alam` : 'Komoditas Perdagangan & Mineral',
    militaryPower: baseMil,
    governmentType: p.type || 'Kedaulatan Berdaulat',
    relationsWithIndonesia: '+80% (Bilateral Terbuka)',
    description: `Kedaulatan berdaulat di ${p.continent} (${p.subregion || ''}). Menjalin hubungan kerja sama bilateral, perdagangan komoditas, dan diplomasi internasional dengan Republik Indonesia.`
  };
};

// Find country by ID or ISO from curated list or loaded geojson
export const getWorldRegionById = (id, worldCountriesGeoData = null) => {
  if (!id) return null;
  const curated = WORLD_REGIONS.find((w) => w.id === id || w.iso3?.toLowerCase() === id.toLowerCase());
  if (curated) return curated;

  if (worldCountriesGeoData && worldCountriesGeoData.features) {
    const feature = worldCountriesGeoData.features.find((f) => {
      const p = f.properties;
      const iso3 = (p.iso_a3 || p.adm0_a3 || '').toLowerCase();
      const cId = (iso3 || p.name || '').toLowerCase().replace(/[^a-z0-9]/g, '_');
      return cId === id.toLowerCase() || iso3 === id.toLowerCase();
    });
    if (feature) {
      return getWorldCountryData(feature);
    }
  }

  return WORLD_REGIONS[0];
};
