export const isoToFlag = (iso) => {
  if (!iso || iso.length !== 2) return '🌐';
  try {
    return iso.toUpperCase().replace(/./g, (char) => String.fromCodePoint(127397 + char.charCodeAt()));
  } catch {
    return '🌐';
  }
};

export const getSectorFromContinent = (continent, subregion) => {
  if (subregion === 'South-Eastern Asia') return 'asean';
  if (continent === 'Oceania') return 'africa_oceania';
  if (continent === 'Asia') {
    if (subregion === 'Eastern Asia') return 'east_asia';
    return 'mid_east_south';
  }
  if (continent === 'Europe') return 'europe';
  if (continent === 'North America' || continent === 'South America') return 'americas';
  if (continent === 'Africa') return 'africa_oceania';
  return 'all';
};

